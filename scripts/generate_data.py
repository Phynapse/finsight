def build_budgets(transactions: list[dict[str, object]]) -> list[dict[str, object]]:
    actual: dict[tuple[str, str, str], float] = defaultdict(float)
    for row in transactions:
        key = (str(row["period"]), str(row["department"]), str(row["category"]))
        amount = float(str(row["amount"]))
        sign = 1.0 if row["transaction_type"] == "expense" else -1.0
        actual[key] = round(actual[key] + sign * amount, TWO_DP)

    rng = random.Random(SEED + 1)
    rows: list[dict[str, object]] = []

    def add_line(period: str, department: str, category: str, actual_amount: float, budget_amount: float) -> None:
        variance = round(actual_amount - budget_amount, TWO_DP)
        variance_pct = None
        if budget_amount != 0:
            variance_pct = round(variance / budget_amount * 100.0, 2)
        rows.append(
            {
                "period": period,
                "quarter": period_of(date(int(period[:4]), int(period[5:7]), 1)),
                "department": department,
                "category": category,
                "budget_amount": f"{budget_amount:.2f}",
                "actual_amount": f"{actual_amount:.2f}",
                "variance_amount": f"{variance:.2f}",
                "variance_pct": "" if variance_pct is None else f"{variance_pct:.2f}",
                "utilisation_pct": "" if budget_amount == 0 else f"{round(actual_amount / budget_amount * 100.0, 2):.2f}",
            }
        )

    for (period, department, category), actual_amount in sorted(actual.items()):
        factor = BUDGET_POSTURE.get((department, category), 1.08)
        budget_amount = round(actual_amount * factor * (1.0 + rng.uniform(-0.04, 0.04)), TWO_DP)
        add_line(period, department, category, actual_amount, budget_amount)

    for period, department, category, budget_amount in UNUSED_BUDGET_LINES:
        add_line(period, department, category, 0.00, round(budget_amount, TWO_DP))

    rows.sort(key=lambda row: (row["period"], row["department"], row["category"]))
    return rows


def build_vendors(transactions: list[dict[str, object]]) -> list[dict[str, object]]:
    spend: dict[str, float] = defaultdict(float)
    counts: dict[str, int] = defaultdict(int)
    for row in transactions:
        vendor_id = str(row["vendor_id"])
        if not vendor_id:
            continue
        amount = float(str(row["amount"]))
        sign = 1.0 if row["transaction_type"] == "expense" else -1.0
        spend[vendor_id] = round(spend[vendor_id] + sign * amount, TWO_DP)
        if row["transaction_type"] == "expense":
            counts[vendor_id] += 1

    rows: list[dict[str, object]] = []
    for vendor_id, vendor_name, department, category, _share, contract_type, start, end in sorted(
        VENDOR_PLAN, key=lambda plan: plan[0]
    ):
        total = spend[vendor_id]
        count = counts[vendor_id]
        average = round(total / count, TWO_DP) if count else 0.00
        status = "active" if end >= "2026-01-01" else "expiring"
        rows.append(
            {
                "vendor_id": vendor_id,
                "vendor_name": vendor_name,
                "category": category,
                "department": department,
                "monthly_spend": f"{round(total / 12.0, TWO_DP):.2f}",
                "total_spend_2024": f"{total:.2f}",
                "transaction_count_2024": count,
                "avg_transaction_amount": f"{average:.2f}",
                "contract_type": contract_type,
                "contract_start": start,
                "contract_end": end,
                "status": status,
            }
        )
    return rows


