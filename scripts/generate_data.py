"""Deterministic generator for the FinSight synthetic financial dataset.

The CSVs committed under ``data/`` are produced by this script so that the
dataset can be regenerated byte-for-byte and audited.  No randomness is taken
from wall-clock time; a fixed seed drives every "random" choice.

Design contract
---------------
The generated data is internally consistent by construction:

1. ``gross_profit = revenue - cogs``
2. ``operating_income = gross_profit - operating_expenses``
3. ``operating_expenses = cash_operating_expenses + non_cash_operating_expenses``
4. For every quarter of FY2024, the net cash expense recorded in
   ``transactions.csv`` equals ``financial_data.cash_operating_expenses`` for
   that quarter.
5. For every (month, department, category) key, ``budgets.actual_amount``
   equals the net expense in ``transactions.csv`` for the same key, and the
   derived variance / utilisation columns are consistent with it.
6. ``vendors.total_spend_2024`` equals the net spend (expenses less credit
   memos) booked against that ``vendor_id`` in FY2024, and
   ``vendors.monthly_spend = round(total_spend_2024 / 12, 2)``. Every cash
   transaction carries a ``vendor_id`` that exists in ``vendors.csv``.
7. ``cash_balance = cash_begin + operating + investing + financing`` and
   ``cash_begin(t) = cash_balance(t - 1)``.

Sign convention: ``amount`` is always a positive magnitude.
``transaction_type = expense`` increases spend, ``credit`` reduces it, so net
spend is ``sum(expense amounts) - sum(credit amounts)``.

``vendor_id`` identifies a supplier relationship *within one cost centre*. The
same legal supplier can therefore appear under several vendor ids (Meridian
Payroll Services serves three departments), which is how real spend systems
model shared service providers.

The narrative encoded in the numbers (the demo question is "why did operating
expenses increase in Q3?"):

* FY2024 Q3 operating expenses rise by +550,000 USD versus Q2 (+10.09%).
* Cash operating expenses rise by +470,000, driven mainly by
  Marketing & Advertising (+240,000, a product launch campaign) and
  Professional Services (+150,000, acquisition diligence and audit work).
* Non-cash operating expenses rise by +80,000 because a new office build-out
  was placed in service, lifting depreciation and amortisation.

Run with::

    python scripts/generate_data.py
"""

